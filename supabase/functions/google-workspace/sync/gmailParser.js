import { base64ToBytes, decodeEncodedWords, headerMap, parseAddress, parseDisplayName } from './mailHeaders.js';
import { extractLeadContact, isAutoGenerated } from './leadNotification.js';

export const MAX_BODY_CHARS = 8000;
export const EMPTY_BODY_TEXT = '(Mensaje sin texto)';

const SKIPPED_LABELS = {
  SENT: 'sent',
  DRAFT: 'draft',
  SPAM: 'spam',
  TRASH: 'trash',
};
const BOUNCE_SENDER = /^(mailer-daemon|postmaster)@/i;
const QUOTE_HEADER = /^(El .+ escribi[óo]:|On .+ wrote:)$/i;
const MESSAGE_ID_PATTERN = /^<[^<>\s]{1,250}>$/;
const MAX_REFERENCES_CHARS = 4000;

function messageIdHeader(value) {
  const trimmed = String(value ?? '').trim();
  return MESSAGE_ID_PATTERN.test(trimmed) ? trimmed : null;
}

export function decodeBodyData(data) {
  if (typeof data !== 'string' || data.length === 0) return '';
  const base64 = data.replace(/-/g, '+').replace(/_/g, '/');
  const padded = base64 + '='.repeat((4 - (base64.length % 4)) % 4);
  return new TextDecoder('utf-8').decode(base64ToBytes(padded));
}

function stripHtml(html) {
  return html
    .replace(/<(style|script)[\s\S]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>|<\/(p|div|li|tr)>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/gi, '&');
}

function collectParts(part, found = { plain: [], html: [] }) {
  if (!part) return found;
  if (part.mimeType === 'text/plain') found.plain.push(decodeBodyData(part.body?.data));
  if (part.mimeType === 'text/html') found.html.push(decodeBodyData(part.body?.data));
  for (const child of part.parts ?? []) collectParts(child, found);
  return found;
}

export function extractText(payload) {
  const { plain, html } = collectParts(payload);
  const firstPlain = plain.find((text) => text.trim().length > 0);
  if (firstPlain) return firstPlain;
  const firstHtml = html.find((text) => text.trim().length > 0);
  return firstHtml ? stripHtml(firstHtml) : '';
}

export function cleanBody(text) {
  const lines = String(text ?? '').replace(/\r\n?/g, '\n').split('\n');
  const kept = [];
  for (const line of lines) {
    if (QUOTE_HEADER.test(line.trim())) break;
    if (line.trimStart().startsWith('>')) continue;
    kept.push(line.replace(/[ \t]+$/g, ''));
  }
  const collapsed = kept.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  if (collapsed.length === 0) return EMPTY_BODY_TEXT;
  return collapsed.slice(0, MAX_BODY_CHARS);
}

function skipReason(message, headers, fromAddress, mailbox, trustedForm) {
  const label = (message.labelIds ?? []).find((name) => SKIPPED_LABELS[name]);
  if (label) return SKIPPED_LABELS[label];
  if (fromAddress === '') return 'no-sender';
  if (fromAddress === mailbox) return 'self';
  if (BOUNCE_SENDER.test(fromAddress)) return 'bounce';
  const contentType = (headers['content-type'] ?? '').toLowerCase();
  if (contentType.startsWith('multipart/report')) return 'bounce';
  const autoSubmitted = (headers['auto-submitted'] ?? '').toLowerCase();
  if (autoSubmitted && autoSubmitted !== 'no' && !trustedForm) return 'automated';
  return null;
}

export function parseGmailMessage(message, mailbox, { trustedSenders = new Set() } = {}) {
  const headers = headerMap(message.payload?.headers);
  const fromAddress = parseAddress(headers.from);
  const trustedForm = trustedSenders.has(fromAddress) && isAutoGenerated(headers);
  const reason = skipReason(message, headers, fromAddress, mailbox, trustedForm);
  if (reason) return { skip: reason };

  const sentAtMs = Number(message.internalDate);
  if (!Number.isFinite(sentAtMs) || sentAtMs <= 0) return { skip: 'no-date' };

  const body = cleanBody(extractText(message.payload));
  const replyTo = parseAddress(headers['reply-to']);
  const contact = trustedForm
    ? extractLeadContact({
        bodyText: body,
        replyTo,
        replyToName: parseDisplayName(headers['reply-to']),
        fromAddress,
        mailbox,
      })
    : { email: fromAddress, name: parseDisplayName(headers.from), phone: '' };
  if (!contact) return { skip: 'no-contact' };

  return {
    record: {
      gmailMessageId: String(message.id ?? ''),
      gmailThreadId: String(message.threadId ?? ''),
      fromAddress,
      fromName: parseDisplayName(headers.from),
      replyTo,
      subject: decodeEncodedWords(headers.subject ?? '').trim(),
      sentAt: new Date(sentAtMs).toISOString(),
      body,
      contactEmail: contact.email,
      contactName: contact.name,
      contactPhone: contact.phone,
      rfcMessageId: messageIdHeader(headers['message-id']),
      references: String(headers.references ?? '').trim().slice(0, MAX_REFERENCES_CHARS),
      viaNotification: trustedForm,
    },
  };
}
