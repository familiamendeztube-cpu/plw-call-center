import { parseAddress } from './mailHeaders.js';

const MIN_PHONE_DIGITS = 7;
const MAX_PHONE_CHARS = 40;
const MAX_NAME_CHARS = 160;
const PHONE_CHARS = /^[+()\-.\s\d]+$/;
const FIELD_LABELS = {
  name: /^\s*(?:nombre(?: completo)?|name|full name)\s*:\s*(.*)$/im,
  phone: /^\s*(?:tel[eé]fono|tel|celular|m[oó]vil|whats\s?app|phone)\s*:\s*(.*)$/im,
  email: /^\s*(?:correo(?: electr[oó]nico)?|e-?mail)\s*:\s*(.*)$/im,
};

export function isAutoGenerated(headers) {
  return (headers['auto-submitted'] ?? '').toLowerCase() === 'auto-generated';
}

export function extractLeadContact({ bodyText, replyTo, replyToName, fromAddress, mailbox }) {
  const formEmail = parseAddress(readField(bodyText, 'email'));
  const email =
    [replyTo, formEmail].find(
      (address) => address && address !== fromAddress && address !== mailbox,
    ) ?? '';
  const phone = normalizePhone(readField(bodyText, 'phone'));
  if (!email && !phone) return null;

  const formName = readField(bodyText, 'name').slice(0, MAX_NAME_CHARS);
  const headerName = email && email === replyTo ? replyToName.slice(0, MAX_NAME_CHARS) : '';
  return { email, name: formName || headerName, phone };
}

function readField(text, key) {
  const match = FIELD_LABELS[key].exec(text);
  return match ? match[1].trim() : '';
}

function normalizePhone(value) {
  if (!PHONE_CHARS.test(value)) return '';
  if (value.replace(/\D/g, '').length < MIN_PHONE_DIGITS) return '';
  return value.trim().slice(0, MAX_PHONE_CHARS);
}
