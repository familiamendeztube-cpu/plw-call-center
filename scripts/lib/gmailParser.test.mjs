test('auto-generated mail from an untrusted sender stays excluded even with a customer Reply-To', () => {
  const parsed = parseGmailMessage(
    makeMessage('u1', {
      from: 'Otro Sistema <avisos@otro.example>',
      headers: [autoGenerated, header('Reply-To', 'cliente@negocio.com')],
    }),
    MAILBOX,
    { trustedSenders: trusted },
  );
  assert.equal(parsed.skip, 'automated');
});

test('a trusted sender vacation or auto-reply is still excluded', () => {
  const parsed = parseGmailMessage(
    makeMessage('v1', {
      from: 'Formulario Web <forms@sitio.example>',
      headers: [header('Auto-Submitted', 'auto-replied'), header('Reply-To', 'cliente@negocio.com')],
      text: 'Nombre: Carla',
    }),
    MAILBOX,
    { trustedSenders: trusted },
  );
  assert.equal(parsed.skip, 'automated');
});

test('an inbound message with no trusted list keeps the old exclusion rules', () => {
  const parsed = parseGmailMessage(
    makeMessage('n1', { from: 'Formulario Web <forms@sitio.example>', headers: [autoGenerated] }),
    MAILBOX,
  );
  assert.equal(parsed.skip, 'automated');
});

test('HTML-only mail is reduced to plain text without markup', () => {
  const html = '<p>Hola&nbsp;<b>equipo</b></p><script>alert(1)</script><div>Gracias &amp; saludos</div>';
  const message = {
    id: 'h1',
    threadId: 'th-h',
    labelIds: ['INBOX'],
    internalDate: String(Date.parse('2026-10-15T12:00:00.000Z')),
    payload: {
      mimeType: 'text/html',
      headers: [header('From', 'b@c.com')],
      body: { data: Buffer.from(html).toString('base64url') },
    },
  };
  const parsed = parseGmailMessage(message, MAILBOX);
  assert.ok(!parsed.record.body.includes('<'));
  assert.ok(!parsed.record.body.includes('alert'));
  assert.match(parsed.record.body, /Gracias & saludos/);
});

